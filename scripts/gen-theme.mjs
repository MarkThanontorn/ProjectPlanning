// Generates src/theme.css: Tailwind palette colours as CSS variables, with a
// dark theme that mirrors each scale (50 ↔ 950, 100 ↔ 900, …) and maps white to slate-900.
// Run: node scripts/gen-theme.mjs   (only needed if the family list changes)
import { writeFileSync } from 'node:fs';
import colors from 'tailwindcss/colors.js';

export const FAMILIES = ['slate', 'emerald', 'rose', 'sky', 'amber', 'violet', 'blue'];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const rgb = (hex) => {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255} ${(n >> 8) & 255} ${n & 255}`;
};
const mirror = (s) => (s === 50 ? 950 : s === 950 ? 50 : 1000 - s);

const light = [`  --c-white: 255 255 255;`];
const dark = [`  --c-white: ${rgb(colors.slate[900])};`];
for (const f of FAMILIES) {
  for (const s of SHADES) {
    light.push(`  --c-${f}-${s}: ${rgb(colors[f][s])};`);
    dark.push(`  --c-${f}-${s}: ${rgb(colors[f][mirror(s)])};`);
  }
}

writeFileSync(
  new URL('../src/theme.css', import.meta.url),
  `/* Generated by scripts/gen-theme.mjs — do not edit by hand. */
:root {
${light.join('\n')}
  --hl: 253 230 138; /* title highlighter (amber-200) */
  color-scheme: light;
}
.dark {
${dark.join('\n')}
  --hl: 146 64 14; /* darker highlighter so light text stays readable */
  color-scheme: dark;
}
`,
);
console.log('wrote src/theme.css');
